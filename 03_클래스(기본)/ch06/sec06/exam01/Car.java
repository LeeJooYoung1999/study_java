package ch06.sec06.exam01;
// 다음과 같이 Car클래스를 정의한 경우, 각 멤버변수가 가지는 기본값은 무엇인가?
public class Car {
    //필드 선언
    String model;
    boolean start;
    int speed;
}

//각 멤버변수 기본값 예상
// model은 String으로 정의된 문자열이므로, 문자열의 기본값인 null일것으로 예상됨.
// start는 boolean으로 정의된 논리형 변수이므로, 기본값으로는 false값을 가질것으로 예상됨.
// speed는 int로 정의된 정수형 변수이므로, 기본값으로는 0을 가질것으로 예상됨.